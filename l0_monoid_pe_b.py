def monoid_multiplicative(gens, max_n: int = 50000, max_elems: int = 5000) -> set[int]:
    """Monoid generated by gens under multiplication, truncated by size."""
    M = {1}
    changed = True
    while changed and len(M) < max_elems:
        changed = False
        add = set()
        for m in M:
            for g in gens:
                p = m * g
                if p <= max_n and p not in M:
                    add.add(p)
        if add:
            M |= add
            changed = True
    return M


def monoid_with_additive(M_mult: set[int], max_n: int = 50000, rounds: int = 3) -> set[int]:
    """
    Close under selected short sums: if a,b in monoid (or gens), allow a+b if ≤ max_n,
    then re-multiply a few rounds (saturation under catalogue-style sums).
    """
    M = set(M_mult)
    gens = set(GEN_MULT_EXT) | {1}
    for _ in range(rounds):
        base = list(M | gens)
        new = set()
        # all pairs of small elements
        small = [a for a in base if a <= 2000]
        for i, a in enumerate(small):
            for b in small[i:]:
                s = a + b
                if s <= max_n:
                    new.add(s)
        # named additive pairs from catalogue
        for a, b in [(61, 27), (61, 3), (80, 3), (80, 8), (539, 1), (3, 6), (9, 9)]:
            if a + b <= max_n:
                new.add(a + b)
        # multiply new by gens
        grow = set()
        for n in new:
            if n not in M:
                grow.add(n)
            for g in GEN_MULT:
                p = n * g
                if p <= max_n:
                    grow.add(p)
        if not grow - M:
            M |= new
            break
        M |= grow
    return M


def is_3_smooth(n: int) -> bool:
    if n <= 0:
        return False
    while n % 3 == 0:
        n //= 3
    return n == 1


def is_3_smooth_times_S(n: int, S=(61, 80, 539)) -> bool:
    """n = 3^a * product S-powers."""
    if n <= 0:
        return False
    n = abs(n)
    for p in (3,) + tuple(S):
        while n % p == 0:
            n //= p
    return n == 1


def factor_resonant(n: int) -> dict:
    """Factor using resonant primes {2,3,5,61,80→16*5, 539→7*7*11} carefully."""
    # Use ordinary factorint
    return dict(sp.factorint(abs(int(n)))) if n else {}


