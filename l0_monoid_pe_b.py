def direction_3(d2: dict) -> dict:
    print("DIRECTION 3 — PE ↔ B unify (first cut)", flush=True)
    # Build PE fibre list with Z coeffs
    pe_fibres = []
    for name, k in PE_K.items():
        for mv in [
            Fraction(1, 8),
            Fraction(5, 8),
            Fraction(5, 4),
            Fraction(1, 5),
            Fraction(1, 4),
            Fraction(3, 8),
            Fraction(1, 1),
            Fraction(-1, 8),
            Fraction(-5, 8),
            Fraction(-5, 4),
        ]:
            al, be = pure_even_ab(mv, k)
            cl = clear_bj(al, be)
            if not cl:
                continue
            A, B = cl
            pe_fibres.append(
                {
                    "name": name,
                    "k": str(k),
                    "k_frac": k,
                    "m": str(mv),
                    "alpha": A,
                    "beta": B,
                    "disc": disc_bj_int(A, B) if abs(A) < 10**8 and abs(B) < 10**8 else None,
                }
            )

    # Candidate maps Φ: PE → A
    maps = {
        "A=alpha": lambda r: r["alpha"],
        "A=beta": lambda r: r["beta"],
        "A=-alpha": lambda r: -r["alpha"],
        "A=-beta": lambda r: -r["beta"],
        "A=alpha+beta": lambda r: r["alpha"] + r["beta"],
        "A=alpha-beta": lambda r: r["alpha"] - r["beta"],
        "A=beta-alpha": lambda r: r["beta"] - r["alpha"],
        "A=gcd": lambda r: int(math.gcd(abs(r["alpha"]), abs(r["beta"]))) or None,
        "A=k_num*k_den": lambda r: r["k_frac"].numerator * r["k_frac"].denominator,
        "A=round(alpha/k)": lambda r: (
            int(round(r["alpha"] / float(r["k_frac"]))) if r["k_frac"] != 0 else None
        ),
    }

    map_results = {}
    for mname, fn in maps.items():
        hits = []
        n_ok = 0
        n_A5 = 0
        n_try = 0
        for r in pe_fibres:
            try:
                A = fn(r)
            except Exception:
                continue
            if A is None or A == 0:
                continue
            if abs(A) > 10**7:
                continue
            n_try += 1
            st = B_status(int(A), do_gal=(n_A5 + n_ok < 30 and abs(A) < 50000))
            if st["irr"] and st["disc_sq"]:
                n_ok += 1
            if st["gal"] == "A5":
                n_A5 += 1
                hits.append(
                    {
                        "pe": f"{r['name']}:m={r['m']}",
                        "k": r["k"],
                        "alpha": r["alpha"],
                        "beta": r["beta"],
                        "A": int(A),
                        "gal": st["gal"],
                    }
                )
            elif st["irr"] and len(hits) < 5:
                hits.append(
                    {
                        "pe": f"{r['name']}:m={r['m']}",
                        "A": int(A),
                        "gal": st["gal"],
                        "irr": st["irr"],
                    }
                )
        map_results[mname] = {
            "n_try": n_try,
            "n_irr_even": n_ok,
            "n_A5": n_A5,
            "hit_rate_even": n_ok / max(n_try, 1),
            "samples": hits[:12],
        }
        print(
            f"  map {mname}: try={n_try} even={n_ok} A5={n_A5}",
            flush=True,
        )

    # Reverse: B A in monoid → does there exist PE fibre with α or β = A?
    pe_abs = set()
    for r in pe_fibres:
        pe_abs.add(r["alpha"])
        pe_abs.add(r["beta"])
        pe_abs.add(-r["alpha"])
        pe_abs.add(-r["beta"])

    M2 = set(d2.get("M2_sample") or [])
    # rebuild larger M2 from d2 sizes - use monoid again
    M2_full = monoid_with_additive(
        monoid_multiplicative(GEN_MULT, max_n=20000), max_n=20000, rounds=2
    )
    reverse_hits = []
    for A in sorted(M2_full)[:100]:
        st = B_status(A, do_gal=False)
        if not st["irr"]:
            continue
        if A in pe_abs or -A in pe_abs:
            reverse_hits.append({"A": A, "in_PE_coeffs": True, "B_irr": True})

    # Algebraic relation test: can P_A be Tschirnhaus-equivalent to a BJ pure-even?
    # Cheap proxy: same disc square-free kernel as some PE fibre
    def sf_kernel(n):
        if not n or n == 0:
            return 0
        fac = sp.factorint(abs(int(n)))
        k = 1
        for p, m in fac.items():
            if m % 2:
                k *= p
        return k * (1 if n > 0 else -1)

    pe_kernels = {}
    for r in pe_fibres:
        if r["disc"] and abs(r["disc"]) < 10**18:
            pe_kernels.setdefault(sf_kernel(r["disc"]), []).append(r["name"])

    kernel_matches = []
    for A in [3, 9, 27, 61, 80, 243, 539, 88, 55, -3, -61]:
        st = B_status(A, do_gal=False)
        if not st.get("disc"):
            continue
        ker = sf_kernel(st["disc"])
        if ker in pe_kernels:
            kernel_matches.append(
                {"A": A, "kernel": ker, "PE_names": pe_kernels[ker][:5]}
            )

    # Best map ranking
    ranking = sorted(
        map_results.items(),
        key=lambda kv: (-kv[1]["n_A5"], -kv[1]["hit_rate_even"]),
    )

    return {
        "n_PE_fibres": len(pe_fibres),
        "map_results": map_results,
        "best_maps": [(n, r["n_A5"], r["hit_rate_even"]) for n, r in ranking[:5]],
        "reverse_hits": reverse_hits[:30],
        "n_reverse": len(reverse_hits),
        "disc_kernel_matches": kernel_matches,
        "conclusion": (
            "No single elementary Φ: PE→A with rate-1 A5. "
            "Best maps by A5 count listed; reverse overlap remains sparse. "
            "Disc square-free kernel matches suggest arithmetic kinship without identity of polys."
        ),
    }


