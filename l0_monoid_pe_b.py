def direction_2() -> dict:
    print("DIRECTION 2 — monoid / saturation", flush=True)
    max_n = 30000
    M0 = monoid_multiplicative(GEN_MULT, max_n=max_n)
    M1 = monoid_multiplicative(GEN_MULT_EXT, max_n=max_n)
    M2 = monoid_with_additive(M0, max_n=max_n, rounds=2)
    print(f"  |M_mult|={len(M0)} |M_ext|={len(M1)} |M_add|={len(M2)}", flush=True)

    # 3-smooth integers up to bound
    smooth3 = []
    p = 1
    while p <= max_n:
        smooth3.append(p)
        p *= 3
    # also 3^a up to max

    # Saturation: which 3-smooth are in monoid?
    hit_smooth = [s for s in smooth3 if s in M2 or s in M0]
    miss_smooth = [s for s in smooth3 if s not in M2]

    # Resonant-smooth: 3^a * 61^b * 80^c * 243^d * 539^e
    # Count how many ≤ max_n lie in pure mult monoid (should be all of M0)
    def enum_resonant_smooth(max_n):
        out = set()
        # 80=16*5=2^4*5, 539=7^2*11 — so mult monoid is NOT 3-smooth
        # "resonant smooth" = only primes dividing some generator
        primes_allowed = set()
        for g in GEN_MULT:
            primes_allowed |= set(sp.factorint(g))
        # generate all products
        # recursive
        from functools import lru_cache

        gens_pf = [dict(sp.factorint(g)) for g in GEN_MULT]

        def rec(i, cur):
            if cur > max_n:
                return
            if i == len(GEN_MULT):
                out.add(cur)
                return
            g = GEN_MULT[i]
            pwr = 1
            while cur * pwr <= max_n:
                rec(i + 1, cur * pwr)
                if pwr > max_n // g:
                    break
                pwr *= g

        rec(0, 1)
        return out

    Rsmooth = enum_resonant_smooth(max_n)
    print(f"  resonant-smooth count ≤{max_n}: {len(Rsmooth)}", flush=True)
    # M0 should equal Rsmooth if monoid is free products of gens
    # Actually monoid from gens is exactly products of gens = resonant mult set
    missing_from_M0 = sorted(Rsmooth - M0)[:20]
    extra_M0 = sorted(M0 - Rsmooth)[:20]

    # Residue classes of monoid mod 3^m
    res_mod = {}
    for m in (1, 2, 3, 4, 5):
        mod = 3**m
        classes = sorted({n % mod for n in M2 if n > 0})
        res_mod[m] = {
            "mod": mod,
            "n_classes": len(classes),
            "classes_sample": classes[:40],
            "density_proxy": len(classes) / mod,
        }

    # k residues for PE catalogue
    k_res = {}
    for m in (1, 2, 3, 4):
        mod = 3**m
        # k as rational - look at num, den mod
        classes = set()
        for name, k in PE_K.items():
            # store k mod via (num * inv den) if den invertible
            num, den = k.numerator, k.denominator
            if math.gcd(den, mod) == 1:
                inv = pow(den % mod, -1, mod)
                classes.add((num * inv) % mod)
            else:
                classes.add(f"den_not_inv:{k}")
        k_res[m] = list(classes)

    # A residues for B: A in ±M2 sample
    A_pool = sorted(M2)[:500] + sorted({-n for n in list(M2)[:200]})
    A_mod = {}
    for m in (1, 2, 3, 4):
        mod = 3**m
        A_mod[m] = sorted({a % mod for a in A_pool})

    # B-embed on monoid elements: irr / A5 rate
    print("  B-status on monoid sample...", flush=True)
    B_on_M = []
    n_gal = 0
    sample_M = sorted(M2)[:80] + [3, 9, 27, 61, 80, 243, 539, 88, 4880]
