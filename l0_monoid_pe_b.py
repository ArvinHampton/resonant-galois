def pure_even_ab(m: Fraction, k: Fraction):
    al = 256 * m**2 - Fraction(3125) * k**4 / 256
    return al, k * al


def clear_bj(al: Fraction, be: Fraction):
    if al == 0:
        return None
    ar, br = Fraction(al), Fraction(be)
    D = int(sp.ilcm(ar.denominator, br.denominator))
    return int(ar * D**4), int(br * D**5)


def B_status(A: int, do_gal: bool = False) -> dict:
    chi = x**5 + 75 * x**3 + A * x**2 + 3 * A
    pol = sp.Poly(chi, x, domain=sp.ZZ)
    if not pol.is_irreducible:
        return {"A": A, "irr": False, "disc_sq": False, "gal": "red"}
    disc = int(pol.discriminant())
    sq = disc > 0 and is_square(disc)
    gal = "even"
    if do_gal and sq:
        cl = classify_poly(chi, do_galois=True)
        st = str(cl.get("status") or "")
        g = str(cl.get("galois") or "")
        if st.startswith("HIT_A5") or "A5" in g:
            gal = "A5"
        elif "D5" in g:
            gal = "D5"
        else:
            gal = "even_other"
    return {"A": A, "irr": True, "disc_sq": sq, "gal": gal, "disc": disc}


